-- Run this once in the Supabase SQL Editor for your project.
create table if not exists public.vehicles (
  id bigint generated by default as identity primary key,
  name text not null,
  registration text not null,
  make text,
  model text,
  year integer,
  insurance_expiry date,
  service_due date,
  licence_expiry date,
  emissions_expiry date,
  notes text,
  created_at timestamptz not null default now()
);

alter table public.vehicles enable row level security;
-- Shared publicly so visitors can view and add entries without signing in.
drop policy if exists "Anyone can view vehicles" on public.vehicles;
create policy "Anyone can view vehicles" on public.vehicles for select to anon, authenticated using (true);
drop policy if exists "Anyone can add vehicles" on public.vehicles;
create policy "Anyone can add vehicles" on public.vehicles for insert to anon, authenticated with check (true);
grant usage on schema public to anon, authenticated;
grant select, insert on public.vehicles to anon, authenticated;
grant usage, select on sequence public.vehicles_id_seq to anon, authenticated;
